#!/usr/bin/env node
// Blur placeholders (LQIPs) for the full-size design photos served as is from public/designs: each
// room's hero and its rendered views. BlurImg (src/components/atom/blur-img.tsx) paints them under
// the photo so it arrives blurred and sharpens, instead of popping out of a flat box.
//
//   pnpm site:blur      run again after adding or replacing a hero or *-real render
//
// Output (committed; the build never runs this script): src/lib/design-blur.generated.ts
import { readdirSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import sharp from "sharp"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const DESIGNS = join(ROOT, "public", "designs")
const OUT = join(ROOT, "src", "lib", "design-blur.generated.ts")

// Photos only: line drawings, plans and the item cut-outs on white cards stay out.
const PHOTO = /-(hero|real)\.(jpe?g|webp)$/

const entries = []
for (const room of readdirSync(DESIGNS).sort()) {
  const dir = join(DESIGNS, room, "render")
  let files
  try {
    files = readdirSync(dir)
  } catch {
    continue
  }
  for (const file of files.filter((f) => PHOTO.test(f)).sort()) {
    const buf = await sharp(join(dir, file)).resize(16).webp({ quality: 50 }).toBuffer()
    entries.push([`/designs/${room}/render/${file}`, `data:image/webp;base64,${buf.toString("base64")}`])
  }
}

writeFileSync(
  OUT,
  `// Generated by scripts/site/design-blur.mjs (pnpm site:blur). Do not edit by hand.\n` +
    `export const DESIGN_BLUR: Record<string, string> = {\n` +
    entries.map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join("\n") +
    `\n}\n`,
)
console.log(`${entries.length} placeholders → ${OUT.slice(ROOT.length + 1)}`)
