#!/usr/bin/env node
// The hero's two photos, one framed for wide screens and one for upright phones.
//
//   pnpm site:hero
//
// Inputs (gitignored): assets/hero/desktop.jpeg, assets/hero/mobile.jpeg (guide.jpeg is the
// founder's styling reference, never served).
// Outputs (committed): public/site/hero/<cut>-<w>.webp at every width in src/lib/image-loader.ts,
// and src/components/home/hero.generated.ts with sizes, blur placeholders and hashed URLs. They
// live outside public/site/img, which pnpm site:assets wipes on every run.
import { createHash } from "node:crypto"
import { mkdirSync, rmSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"
import sharp from "sharp"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..", "..")
const OUT = join(ROOT, "public", "site", "hero")
const MANIFEST = join(ROOT, "src", "components", "home", "hero.generated.ts")
// Keep in step with WIDTHS in src/lib/image-loader.ts.
const WIDTHS = [640, 960, 1280, 1920]
const CUTS = { desktop: "desktop.jpeg", mobile: "mobile.jpeg" }

rmSync(OUT, { recursive: true, force: true })
mkdirSync(OUT, { recursive: true })
const manifest = {}
for (const [cut, file] of Object.entries(CUTS)) {
  const { data, info } = await sharp(join(ROOT, "assets", "hero", file)).rotate().toBuffer({ resolveWithObject: true })
  const served = []
  // Every width, even past the master's, so no srcset entry 404s.
  for (const w of WIDTHS) {
    const quality = { 640: 78, 960: 76, 1280: 72, 1920: 68 }[w]
    const out = await sharp(data).resize({ width: w, withoutEnlargement: true })
      .webp({ quality, effort: 6, smartSubsample: true }).toBuffer()
    writeFileSync(join(OUT, `${cut}-${w}.webp`), out)
    served.push(out)
  }
  const scale = Math.min(1, WIDTHS[WIDTHS.length - 1] / info.width)
  const lqip = await sharp(data).resize({ width: 20 }).webp({ quality: 40 }).toBuffer()
  manifest[cut] = {
    src: `/site/hero/${cut}.webp?v=${createHash("sha1").update(Buffer.concat(served)).digest("hex").slice(0, 8)}`,
    width: Math.round(info.width * scale),
    height: Math.round(info.height * scale),
    blurDataURL: `data:image/webp;base64,${lqip.toString("base64")}`,
  }
  console.log(`hero ${cut} ${manifest[cut].width}×${manifest[cut].height}`)
}

writeFileSync(
  MANIFEST,
  `// Generated by scripts/site/hero.mjs (pnpm site:hero). Do not edit.\n` +
    `export const HERO = ${JSON.stringify(manifest, null, 2)} as const\n`,
)
