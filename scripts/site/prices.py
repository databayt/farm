"""The price catalogue every place's bill of materials reads: the studio generator's unit prices
(scripts/studio/prices.py, label A for a placeholder under AS-21, V for a published price) and the published
prices other places use, taken by their id from study/registers/prices.csv. Writes
src/components/site/prices.json, read by src/lib/bom.ts, so a part costs the same wherever it is used and a quote
recorded once reprices every place.

    python3 scripts/site/prices.py
"""
from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts" / "studio"))
from prices import CONTINGENCY, LABOUR, PRICES, SHARED  # noqa: E402

# Parts the studio does not buy, priced from the register by id: key -> (price id, the unit the price is for)
REGISTER: dict[str, tuple[str, str]] = {
    "lpg_kg": ("ENG-P01", "per kg of LPG, the list price of a 38 kg cylinder's fill"),
    "rdb_licence": ("STU-P09", "the RDB tourism operating licence"),
}


def register_price(pid: str) -> float:
    with open(ROOT / "study" / "registers" / "prices.csv", newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            if row["id"] == pid:
                return float(row["price_rwf"])
    raise SystemExit(f"prices.py: no {pid} in study/registers/prices.csv")


def main() -> None:
    parts = {k: {"rwf": v[0], "label": v[1], "source": v[2], "note": v[3]} for k, v in PRICES.items()}
    for key, (pid, note) in REGISTER.items():
        parts[key] = {"rwf": register_price(pid), "label": "V", "source": pid, "note": note}
    out = {
        "_": "Generated by scripts/site/prices.py from scripts/studio/prices.py and study/registers/prices.csv; do not edit.",
        "contingency": CONTINGENCY,
        "parts": parts,
        "labour": [{"item": i, "rwf": r, "label": l, "source": "AS-21"} for i, r, l in LABOUR],
        "shared": [{"item": i, "rwf": r, "label": l, "source": "AS-21" if l == "A" else "STU-P05"} for i, r, l in SHARED],
    }
    path = ROOT / "src" / "components" / "site" / "prices.json"
    path.write_text(json.dumps(out, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"{path.relative_to(ROOT)}: {len(parts)} parts")


if __name__ == "__main__":
    main()
